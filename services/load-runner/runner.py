from __future__ import annotations

import asyncio
import os
import statistics
import time
from collections import Counter
from datetime import datetime, timezone

import httpx
from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, Field

TARGET_URL = os.getenv("LOAD_TEST_TARGET_URL", "http://api:8000/health/live")
app = FastAPI(title="AegisGrid Load Runner", version="0.1.0")


class RunRequest(BaseModel):
    concurrency: int = Field(default=10, ge=1, le=100)
    duration_seconds: int = Field(default=5, ge=1, le=30)


@app.get("/health/live")
def live():
    return {"status": "alive", "service": "aegisgrid-load-runner"}


def percentile(values: list[float], q: float) -> float | None:
    if not values:
        return None
    ordered = sorted(values)
    index = max(0, min(len(ordered) - 1, int(round((len(ordered) - 1) * q))))
    return round(ordered[index], 3)


@app.post("/run")
async def run_load_test(body: RunRequest):
    started_at = datetime.now(timezone.utc)
    start = time.perf_counter()
    deadline = start + body.duration_seconds
    latencies: list[float] = []
    status_counts: Counter[str] = Counter()
    errors: Counter[str] = Counter()
    total = 0
    succeeded = 0
    lock = asyncio.Lock()
    timeout = httpx.Timeout(3.0, connect=1.0)

    async with httpx.AsyncClient(timeout=timeout, limits=httpx.Limits(max_connections=body.concurrency + 5)) as client:
        async def worker():
            nonlocal total, succeeded
            while time.perf_counter() < deadline:
                sent = time.perf_counter()
                try:
                    response = await client.get(TARGET_URL)
                    latency_ms = (time.perf_counter() - sent) * 1000
                    async with lock:
                        total += 1
                        latencies.append(latency_ms)
                        status_counts[str(response.status_code)] += 1
                        if response.is_success:
                            succeeded += 1
                        else:
                            errors[f"http_{response.status_code}"] += 1
                except Exception as exc:
                    latency_ms = (time.perf_counter() - sent) * 1000
                    async with lock:
                        total += 1
                        latencies.append(latency_ms)
                        errors[type(exc).__name__] += 1

        await asyncio.gather(*(worker() for _ in range(body.concurrency)))

    elapsed = time.perf_counter() - start
    return {
        "run_id": f"LOAD-{started_at.strftime('%Y%m%dT%H%M%S')}-{int(started_at.microsecond / 1000):03d}",
        "target": TARGET_URL,
        "started_at": started_at.isoformat(),
        "duration_requested_seconds": body.duration_seconds,
        "duration_actual_seconds": round(elapsed, 3),
        "concurrency": body.concurrency,
        "requests_total": total,
        "requests_successful": succeeded,
        "requests_failed": total - succeeded,
        "requests_per_second": round(total / elapsed, 3) if elapsed else 0,
        "latency_ms": {
            "min": round(min(latencies), 3) if latencies else None,
            "mean": round(statistics.mean(latencies), 3) if latencies else None,
            "p50": percentile(latencies, .50),
            "p95": percentile(latencies, .95),
            "max": round(max(latencies), 3) if latencies else None,
        },
        "status_counts": dict(status_counts),
        "error_counts": dict(errors),
        "measurement_note": "Measured HTTP requests generated by the independent load-runner container. Target is restricted to the configured health endpoint; numbers vary by local machine and runtime state."
    }
